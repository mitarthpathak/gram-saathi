/**
 * Lists candidate voices from the Gemini Extended Voice Library for a person to audition:
 *
 *   npm run tts:voices -w server
 *
 * Queries GET /v1beta/voices for language_code hi-IN, mr-IN, ta-IN, en-IN and for region_code IN,
 * and writes docs/tts-voice-candidates.md (id, display name, language, accent, gender, pitch,
 * description). It changes no config and never creates, designs or replicates a voice. Needs
 * GEMINI_API_KEY; the key is sent in a header and never printed.
 *
 * Docs: https://ai.google.dev/gemini-api/docs/speech-generation (Extended Voice Library).
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { env } from '../src/config/env';

const VOICES_URL = 'https://generativelanguage.googleapis.com/v1beta/voices';
const DOCS_URL = 'https://ai.google.dev/gemini-api/docs/speech-generation';
const OUT_FILE = path.resolve(__dirname, '../../docs/tts-voice-candidates.md');
const MAX_PAGES = 20;

const QUERIES: Array<{ label: string; params: Record<string, string> }> = [
  { label: 'language_code=hi-IN', params: { language_code: 'hi-IN' } },
  { label: 'language_code=mr-IN', params: { language_code: 'mr-IN' } },
  { label: 'language_code=ta-IN', params: { language_code: 'ta-IN' } },
  { label: 'language_code=en-IN', params: { language_code: 'en-IN' } },
  { label: 'region_code=IN', params: { region_code: 'IN' } },
];

/** The docs show snake_case fields; camelCase is accepted too in case REST returns that. */
type LibraryVoice = Record<string, unknown>;

function field(voice: LibraryVoice, snake: string): string {
  const camel = snake.replace(/_([a-z])/g, (_match, letter: string) => letter.toUpperCase());
  const value = voice[snake] ?? voice[camel];
  if (Array.isArray(value)) return value.join(', ');
  return value === undefined || value === null ? '' : String(value);
}

async function listVoices(apiKey: string, params: Record<string, string>): Promise<LibraryVoice[]> {
  const voices: LibraryVoice[] = [];
  let pageToken = '';
  for (let page = 0; page < MAX_PAGES; page++) {
    const query = new URLSearchParams({ ...params, page_size: '1000' });
    if (pageToken) query.set('page_token', pageToken);
    const response = await fetch(`${VOICES_URL}?${query}`, {
      headers: { 'x-goog-api-key': apiKey },
      signal: AbortSignal.timeout(30_000),
    });
    if (!response.ok) {
      const body = (await response.text().catch(() => '')).slice(0, 300);
      throw new Error(`GET /v1beta/voices?${query} answered HTTP ${response.status}: ${body}`);
    }
    const payload = (await response.json()) as Record<string, unknown>;
    if (Array.isArray(payload.voices)) voices.push(...(payload.voices as LibraryVoice[]));
    pageToken = String(payload.next_page_token ?? payload.nextPageToken ?? '');
    if (!pageToken) break;
  }
  return voices;
}

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

async function main(): Promise<void> {
  const apiKey = env.GEMINI_API_KEY;
  if (!apiKey) {
    console.error('GEMINI_API_KEY is not set. Add it to .env (never commit it) and run again.');
    process.exitCode = 1;
    return;
  }

  const found = new Map<string, { voice: LibraryVoice; matchedBy: Set<string> }>();
  for (const query of QUERIES) {
    const voices = await listVoices(apiKey, query.params);
    console.log(`${query.label}: ${voices.length} voice(s)`);
    for (const voice of voices) {
      const id = field(voice, 'id') || field(voice, 'name');
      if (!id) continue;
      const entry = found.get(id) ?? { voice, matchedBy: new Set<string>() };
      entry.matchedBy.add(query.label);
      found.set(id, entry);
    }
  }

  const rows = [...found.entries()]
    .map(([id, { voice, matchedBy }]) => ({
      id,
      name: field(voice, 'display_name'),
      language: field(voice, 'language_code'),
      accent: field(voice, 'accent'),
      gender: field(voice, 'gender'),
      pitch: field(voice, 'pitch'),
      description: field(voice, 'description'),
      matchedBy: [...matchedBy].join(', '),
    }))
    .sort((a, b) =>
      `${a.language} ${a.accent} ${a.name}`.localeCompare(`${b.language} ${b.accent} ${b.name}`),
    );

  const today = new Date().toISOString().slice(0, 10);
  const lines = [
    '# TTS voice candidates',
    '',
    `Generated by \`npm run tts:voices -w server\` on ${today} from the Gemini Extended Voice Library`,
    `(\`GET /v1beta/voices\`, see ${DOCS_URL}). Queries: ${QUERIES.map((q) => `\`${q.label}\``).join(', ')}.`,
    '',
    'These are **candidates only**. Nothing here has been listened to. To choose a voice: render',
    'samples (`npm run tts:samples -w server` after adding the candidate to',
    '`server/src/config/tts-voices.json` as `{ "voiceId": "<id>", "status": "to-be-auditioned" }`),',
    'have a native speaker listen, and set `"status": "auditioned"` only for voices they approve.',
    'An accent label in this table is the provider’s description, not a verified dialect.',
    '',
    `${rows.length} unique voice(s).`,
    '',
    '| id | display name | language | accent | gender | pitch | description | matched by |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (row) =>
        `| \`${cell(row.id)}\` | ${cell(row.name)} | ${cell(row.language)} | ${cell(row.accent)} | ${cell(row.gender)} | ${cell(row.pitch)} | ${cell(row.description)} | ${cell(row.matchedBy)} |`,
    ),
    '',
  ];
  writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
  console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)} (${rows.length} voices).`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
